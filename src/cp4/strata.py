"""The 39 strata of the maximal-determinant-frame reduction (THEORY.md Thm 6.2).

Frame coordinates: Gamma = Lambda X^{-1} contains Z^4 with index p (p = |det X| / det Lambda),
and Gamma has no nonzero point with ||c||_1 < 1  (points with ||c||_1 = 1 are minimal vectors).
Gamma is stored by its residue group G = p*Gamma / p*Z^4  <=  (Z/p)^4.

Lee criterion: Gamma meets the OPEN unit l1 ball only in 0  <=>  every nonzero residue r has
    sum_j min(r_j, p - r_j) >= p.
(For CLEAN cross-polytopes, the classical six types, the inequality is strict: '> p'.)
"""
from itertools import product, permutations
from fractions import Fraction as F
import json

SIGNED_PERMS = [(pm, sg) for pm in permutations(range(4)) for sg in product((1, -1), repeat=4)]

def _diagonals(p, n):
    if n == 1:
        yield (p,); return
    for d in range(1, p + 1):
        if p % d == 0:
            for ds in _diagonals(p // d, n - 1):
                yield (d,) + ds

def hnfs(p, n=4):
    ij = [(i, j) for i in range(n) for j in range(i + 1, n)]
    for ds in _diagonals(p, n):
        for off in product(*[range(ds[j]) for i, j in ij]):
            H = [[0] * n for _ in range(n)]
            for i in range(n):
                H[i][i] = ds[i]
            for (i, j), a in zip(ij, off):
                H[i][j] = a
            yield H

def lee(r, p):
    return sum(min(x, p - x) for x in r)

def group(gens, p, strict=False):
    """Subgroup of (Z/p)^4 generated by gens, or None if some nonzero element violates Lee."""
    n = len(gens[0]); zero = (0,) * n; seen = {zero}; pend = [zero]
    while pend:
        v = pend.pop()
        for g in gens:
            w = tuple((a + b) % p for a, b in zip(v, g))
            if w in seen:
                continue
            L = lee(w, p)
            if L < p or (strict and L == p):
                return None
            seen.add(w); pend.append(w)
    return frozenset(seen)

def dual_residues(H, p, strict=False):
    n = len(H); J = [[0] * n for _ in range(n)]
    for i in reversed(range(n)):
        J[i][i] = p // H[i][i]
        for j in range(i + 1, n):
            a = -sum(H[i][k] * J[k][j] for k in range(i + 1, j + 1))
            if a % H[i][i]:
                return None
            J[i][j] = a // H[i][i]
    gens = [tuple(J[j][i] % p for j in range(n)) for i in range(n)]
    return group(gens, p, strict)

def act(g, r, p):
    pm, sg = g
    return tuple((sg[k] * r[pm[k]]) % p for k in range(4))

def canon_group(G, p):
    return min(tuple(sorted(act(g, r, p) for r in G)) for g in SIGNED_PERMS)

def stabilizer(G, p):
    Gs = frozenset(G)
    return [g for g in SIGNED_PERMS if frozenset(act(g, r, p) for r in G) == Gs]

def candidates(G, p):
    """Gamma ∩ [-1,1]^4 ∩ {||c||_1 >= 1}, one per +- pair, as integer numerator tuples
    (the point is c = num/p).  Also returns the 'forced' ones with ||c||_1 == 1."""
    out = set()
    for r in G:
        base = [x if x <= p // 2 else x - p for x in r]   # not needed; enumerate shifts
        for sh in product((-1, 0, 1), repeat=4):
            num = tuple(r[k] + p * sh[k] for k in range(4))
            if any(abs(x) > p for x in num):
                continue
            if not any(num):
                continue
            if sum(abs(x) for x in num) < p:
                continue
            m = tuple(-x for x in num)
            out.add(max(num, m))   # canonical: lexicographically larger of +-
    cand = sorted(out)
    forced = [c for c in cand if sum(abs(x) for x in c) == p]
    return cand, forced

def enumerate_strata(pmax=24, strict=False):
    strata = []
    for p in range(1, pmax + 1):
        found = set()
        for H in hnfs(p):
            G = dual_residues(H, p, strict)
            if G is not None:
                found.add(G)
        reps = {}
        for G in found:
            reps.setdefault(canon_group(G, p), G)
        for key in sorted(reps):
            G = frozenset(key)
            cand, forced = candidates(G, p)
            strata.append({'p': p, 'residues': sorted(G), 'n_superlattices_in_orbit':
                           sum(1 for H in found if canon_group(H, p) == key),
                           'candidates': cand, 'forced': forced,
                           'stabilizer_order': len(stabilizer(G, p))})
    for i, s in enumerate(strata):
        s['id'] = i
    return strata

if __name__ == '__main__':
    import sys
    S = enumerate_strata()
    json.dump(S, open(sys.argv[1] if len(sys.argv) > 1 else 'strata.json', 'w'))
    print(len(S), 'strata')
